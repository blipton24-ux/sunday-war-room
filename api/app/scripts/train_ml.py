"""Train the P4 models season by season and compare each target with a simple baseline.

    python -m app.scripts.train_ml                         # test seasons 2022-2025
    python -m app.scripts.train_ml --test 2025 --report ../docs/Build-Plan/ML-Training-Report.md
    python -m app.scripts.train_ml --save models/          # also save the last season's models

For each test season S the models train on every season from --first to S-1 (the last of them
held back to pick settings, ADR-061) and are graded on S. Each target's average miss is shown
beside the baseline: the player's own season-to-date value, else last season's, else his recent
games, else the position's training average. Counts weigh every game alike; rates weigh each
game by its opportunities. Points come in step 6; this report shows whether each part learns.
"""

from __future__ import annotations

import argparse
import asyncio
import sys
import time
from pathlib import Path

import numpy as np
import pandas as pd

from app.db.session import get_engine, get_sessionmaker
from app.model.ml.data import ModelData, load_model_data
from app.model.ml.features import SKILL
from app.model.ml.targets import BY_POSITION, label, naive
from app.model.ml.train import GRID, ModelSet, TrainingTable, save, train_all, training_table

SETTINGS = ("max_depth", "min_child_weight", "colsample_bytree")


def grade(models: ModelSet, train: TrainingTable, test: TrainingTable) -> pd.DataFrame:
    """One row per (position, target): games, model and baseline average miss on `test`."""
    predicted = models.predict(test.features)
    rows = []
    for position in SKILL:
        at = (test.features["position"] == position).to_numpy()
        for target in BY_POSITION[position]:
            if (position, target.name) not in models.models:
                continue
            value, weight = label(test.stats[at], target)
            ok = (weight > 0).to_numpy() & np.isfinite(value.to_numpy())
            y, w = value.to_numpy()[ok], weight.to_numpy()[ok]
            model = predicted[target.name].to_numpy()[at][ok]
            tv, tw = label(train.stats[(train.features["position"] == position).to_numpy()], target)
            tok = (tw > 0) & np.isfinite(tv)
            if not ok.any() or not tok.any():
                continue  # nothing to grade (or no training average to fall back on)
            fallback = float(np.average(tv[tok], weights=tw[tok]))
            base = naive(test.features[at], target).fillna(fallback).to_numpy()[ok]
            fitted = models.models[(position, target.name)]
            rows.append(
                {
                    "position": position,
                    "target": target.name,
                    "kind": target.kind,
                    "games": int(ok.sum()),
                    "model": float(np.average(np.abs(model - y), weights=w)),
                    "baseline": float(np.average(np.abs(base - y), weights=w)),
                    **{s: fitted.params[s] for s in SETTINGS},
                    "trees": fitted.trees,
                }
            )
    out = pd.DataFrame(rows)
    out["change_pct"] = 100 * (out["model"] / out["baseline"] - 1)
    return out


def render(results: pd.DataFrame, first: int, seconds: float) -> str:
    seasons = sorted(results["season"].unique())
    pooled = (
        results.assign(
            m=results["model"] * results["games"], b=results["baseline"] * results["games"]
        )
        .groupby(["position", "target", "kind"], sort=False)[["games", "m", "b"]]
        .sum()
        .reset_index()
    )
    pooled["model"] = pooled["m"] / pooled["games"]
    pooled["baseline"] = pooled["b"] / pooled["games"]
    pooled["change"] = 100 * (pooled["model"] / pooled["baseline"] - 1)
    by_season = results.pivot_table(index=["position", "target"], columns="season",
                                    values="change_pct", sort=False, dropna=False)  # fmt: skip
    better = {
        (str(k[0]), str(k[1])): int(v)
        for k, v in zip(by_season.index.tolist(), (by_season < 0).sum(axis=1), strict=True)
    }
    lines = [
        "---",
        'title: "ML Training Report (P4 step 5)"',
        f"date: {pd.Timestamp.today().date()}",
        "tags: [model, machine-learning, backtest, p4]",
        "---",
        "# ML training report: each target against a simple baseline",
        "",
        f"Generated by `python -m app.scripts.train_ml`. Test seasons {seasons[0]}-{seasons[-1]}, "
        f"each trained on {first} to the season before it (the last training season held back "
        f"to pick settings from {len(GRID)} candidates). Average miss: counts per game, rates "
        "weighted by opportunities. Baseline: the player's own season-to-date value, else last "
        "season's, else his recent games, else the position average. Negative change = the "
        f"model misses less. Run time {seconds / 60:.1f} minutes.",
        "",
        "| Position | Target | Games | Model miss | Baseline miss | Change | Better in seasons |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in pooled.to_dict("records"):
        b = better[(str(r["position"]), str(r["target"]))]
        lines.append(
            f"| {r['position']} | {r['target']} | {int(r['games']):,} | {r['model']:.3f} "
            f"| {r['baseline']:.3f} | {r['change']:+.1f}% | {b} of {len(seasons)} |"
        )
    lines += ["", "## Change by test season", "",
              "| Position | Target | " + " | ".join(str(s) for s in seasons) + " |",
              "|---|---|" + "---|" * len(seasons)]  # fmt: skip
    for key, values in zip(by_season.index.tolist(), by_season.to_numpy(), strict=True):
        cells = " | ".join(f"{v:+.1f}%" for v in values)
        lines.append(f"| {key[0]} | {key[1]} | {cells} |")
    last = results[results["season"] == seasons[-1]]
    lines += ["", f"## Settings picked for {seasons[-1]}", "",
              "| Position | Target | Depth | Min weight per leaf | Column share | Trees |",
              "|---|---|---|---|---|---|"]  # fmt: skip
    for r in last.itertuples():
        lines.append(f"| {r.position} | {r.target} | {r.max_depth} | {r.min_child_weight} "
                     f"| {r.colsample_bytree} | {r.trees} |")  # fmt: skip
    lines += [
        "",
        "Related: [P4 Build Plan](P4-Build-Plan.md) · "
        "[ADR-061](../Decisions/ADR-061-P4-How-The-ML-Model-Is-Tested-And-Shipped.md) · "
        "[Backtest Report](Backtest-Report.md)",
    ]
    return "\n".join(lines) + "\n"


async def _load(seasons: list[int]) -> ModelData:
    async with get_sessionmaker()() as db:
        data = await load_model_data(db, seasons)
    await get_engine().dispose()
    if data.stats.empty:
        raise SystemExit("No nflverse rows in the database: run the ingest_nflverse job first.")
    return data


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--first", type=int, default=2016, help="first training season")
    parser.add_argument("--test", type=int, nargs="+", default=[2022, 2023, 2024, 2025])
    parser.add_argument("--report", type=Path)
    parser.add_argument("--save", type=Path, help="save the models trained for the last season")
    args = parser.parse_args()

    started = time.time()
    data = asyncio.run(_load(list(range(args.first, max(args.test) + 1))))
    table = training_table(data, range(args.first, max(args.test) + 1))
    parts = []
    models = ModelSet()
    for season in sorted(args.test):
        train_seasons = list(range(args.first, season))
        models = train_all(table, train_seasons)
        graded = grade(models, table.seasons(train_seasons), table.seasons([season]))
        parts.append(graded.assign(season=season))
        print(f"done {season}", file=sys.stderr, flush=True)
    text = render(pd.concat(parts, ignore_index=True), args.first, time.time() - started)
    print(text)
    if args.report:
        args.report.write_text(text, encoding="utf-8", newline="\n")
    if args.save:
        save(models, args.save)
        print(f"saved {len(models.models)} models to {args.save}", file=sys.stderr)


if __name__ == "__main__":
    main()
